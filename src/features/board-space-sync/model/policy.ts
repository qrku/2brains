import type { BNode, NodeKind } from '@/entities/board';

/**
 * Виды нод, которым в Пространстве соответствует файл.
 *
 * Список намеренно вынесен отдельной константой, а не зашит условием `kind === 'box'` по коду:
 * он будет расти (карточки, задачи, всё, у чего есть содержание помимо подписи), и добавление
 * нового вида должно быть правкой одной строки, а не поиском по проекту. Рисунки, текстовые
 * подписи и фреймы файлов не получают: у первых двух нет содержания кроме них самих, а фрейм —
 * это папка, а не документ.
 */
export const MIRRORED_KINDS: readonly NodeKind[] = ['box'];

/** Виду этой ноды вообще положен файл. */
export const isMirrored = (node: BNode): boolean => MIRRORED_KINDS.includes(node.kind);

/**
 * Заводит ли эта нода собственный файл.
 *
 * Связанная копия — нет: она показывает файл оригинала и делит его с ним. Если бы зеркало
 * создавало ей свой файл, «связь» свелась бы к двум независимым копиям текста.
 */
export const ownsFile = (node: BNode): boolean => isMirrored(node) && !node.link;

/** Заводит ли этот фрейм собственную папку — по той же причине, что и `ownsFile`. */
export const ownsFolder = (node: BNode): boolean => node.kind === 'frame' && !node.link;
