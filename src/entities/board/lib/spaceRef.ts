/**
 * Ссылка на файл Пространства внутри текста ноды.
 *
 * Нотация — часть формата доски: её пишет меню «/» в редакторе ноды, читает рендер текста
 * и разбирает зеркало нод в файлы, когда собирает имя файла из подписи ноды. Поэтому она
 * живёт в сущности доски, а не в одном из мест использования.
 */

export interface SpaceRef {
  id: string;
  name: string;
}

/** Как ссылка на файл Пространства хранится в тексте ноды. */
export const spaceRefNotation = (ref: SpaceRef) => `[[space:${ref.id}|${ref.name}]]`;

/**
 * Свежая регулярка на каждый вызов: у глобального флага есть `lastIndex`, и один общий
 * экземпляр протекал бы состоянием между вызывающими.
 */
export const spaceRefRe = () => /\[\[space:([^|]+)\|([^\]]+)\]\]/g;

/** Текст ноды, в котором ссылки заменены на их видимую подпись. */
export function stripSpaceRefs(text: string): string {
  return text.replace(spaceRefRe(), (_match, _id, name: string) => name);
}
