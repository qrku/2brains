/**
 * Режимы управления пальцем.
 *
 * Жестов на телефоне мало, а действий на доске много, и раздать одно другому
 * можно по-разному: кому-то важнее, чтобы блок ехал сразу за пальцем, кому-то —
 * чтобы случайное касание ничего не сдвинуло. Правильного ответа тут нет,
 * поэтому раскладка вынесена в настройки.
 *
 * Вся разница между режимами — в этой таблице: новый режим добавляется одной
 * записью, а холст, подсказка и настройки подхватывают его сами. Всё, чего в
 * таблице нет, одинаково везде:
 *
 *   · двойной тап по блоку — правка текста и панель свойств;
 *   · зажатие пустого места — рамка выделения;
 *   · уже выделенный блок едет за пальцем без всяких жестов;
 *   · мышь живёт по своим правилам, режимы её не касаются.
 */

/** Что делает касание блока. */
export type NodeTap =
  /** Сразу тянуть — блок едет за пальцем с первого движения. */
  | 'drag'
  /** Только выделить — сдвинуть можно будет вторым касанием. */
  | 'select';

/** Что делает долгое нажатие на блоке. */
export type NodeHold =
  /** Открыть файл блока в редакторе. Блокам без файла достаётся правка подписи. */
  | 'note'
  /** Открыть на правку подписи вместе с панелью свойств. */
  | 'open'
  /** Взять в руку — дальше блок едет за пальцем. */
  | 'drag';

export interface TouchModeSpec {
  tap: NodeTap;
  hold: NodeHold;
  /** Название в настройках. */
  label: string;
  /** Строка под названием в настройках: вся раскладка целиком, длина не важна. */
  about: string;
  /**
   * То же для всплывающей подсказки на доске, и только про спрятанные жесты: она
   * влезает в одну строку экрана, а про тап человек и так узнаёт, тапнув.
   */
  hint: string;
}

const MODES = {
  default: {
    tap: 'drag',
    hold: 'note',
    label: 'Обычный',
    about: 'Тап — перенос · Зажать — файл блока · Двойной тап — правка',
    hint: 'Зажать — файл · Двойной тап — правка',
  },
  safe: {
    tap: 'select',
    hold: 'drag',
    label: 'Аккуратный',
    about: 'Тап — выделить · Зажать — перенос · Двойной тап — правка',
    hint: 'Зажать — перенос · Двойной тап — правка',
  },
} satisfies Record<string, TouchModeSpec>;

export type TouchMode = keyof typeof MODES;

/**
 * Наружу таблица отдаётся с широкими типами полей: внутри `tap` каждой записи
 * знает своё единственное значение, и проверка «а если здесь будет другое»
 * считалась бы заведомо ложной — ровно те ветки, которые ждут новых режимов.
 */
export const TOUCH_MODES: Record<TouchMode, TouchModeSpec> = MODES;

export const DEF_TOUCH_MODE: TouchMode = 'default';

/** Порядок, в котором режимы стоят в настройках — тот же, что и в таблице. */
export const TOUCH_MODE_LIST = Object.keys(MODES) as TouchMode[];

/** Прочитанное из хранилища могло устареть: режим мог быть переименован или убран. */
export function isTouchMode(value: unknown): value is TouchMode {
  return typeof value === 'string' && value in MODES;
}
